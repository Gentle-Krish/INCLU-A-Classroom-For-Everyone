export const useTranslation = () => {
  const storedLanguage = useStore(state => state.language);
  const language = storedLanguage === 'id' ? 'en' : storedLanguage;
  
  const t = (key: string, fallback?: string): string => {
    const dict = translations[language] || translations['en'] || translations['id'];
    if (dict?.[key]) return dict[key];
    if (translations['en']?.[key]) {
      return translations['en'][key];
    }
    return fallback || translations['en']?.[key] || translations['id']?.[key] || key;
  };

  const currentLangInfo = SUPPORTED_LANGUAGES.find(l => l.code === language) || SUPPORTED_LANGUAGES[0];

  return { t, language, currentLangInfo };
};
